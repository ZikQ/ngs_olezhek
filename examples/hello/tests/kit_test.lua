local function open(t)
    t.Go("/kit")
    t.Settle()
end

test("kit page builds every component without errors", function(t)
    open(t)
    for _, class in ipairs({ "Badge", "Status", "Avatar", "Meter", "Segmented", "Select", "DatePicker",
        "ListView", "Sparkline", "LineChart", "DonutChart", "BarChart", "Spinner", "Icon" }) do
        t.Get(class)
    end
    assert(t.HasText("Сейчас: 26 November 2026, 18:4"), t.Text())
    R.visibility_changed(false)
    assert(t.HasText("Вкладка: скрыта"), t.Text())
end)

test("select, segmented and date pickers report the choice", function(t)
    open(t)
    local select = t.Get("Select")
    t.Click(select)
    t.Click({ Class = "Button", Text = "@mia_vibes" })
    assert(t.HasText("модель: @mia_vibes"), t.Text())
    t.Click({ Class = "Button", Text = "Всё время" })
    assert(t.HasText("период: all"), t.Text())
    local from = t.Get({ Class = "DatePicker", Text = "Дата от" })
    t.Click(from)
    t.Click(from.Calendar.Days:GetChild(6 + 3))
    assert(t.HasText("с 03.11.2026"), t.Text())
end)

test("list view pages, sorts and reacts to clicks", function(t)
    open(t)
    local lv = t.Get("ListView")
    t.Eq(lv.Body:ChildCount(), 8)
    t.Click(lv.MoreButton)
    t.Eq(lv.Body:ChildCount(), 16)
    t.Click(lv.Header:GetChild(4))
    local shown = lv:GetDisplayRows()
    assert(shown[1].amount >= shown[2].amount)
    t.Click(lv.Body:GetChild(1))
    assert(t.HasText(shown[1].model), t.Text())
end)

test("confirm dialog answers through a toast", function(t)
    open(t)
    t.Click({ Class = "Button", Text = "Подтверждение" })
    t.Click({ Class = "Button", Text = "Да" })
    assert(t.HasText("Смена завершена"), t.Text())
end)
